import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const git = (args, cwd = root) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const remote = git(['remote', 'get-url', 'origin']);
const match = remote.match(
  /^(?:https:\/\/github\.com\/|git@github\.com:)([\w-]+)\/([\w.-]+?)(?:\.git)?$/,
);
if (!match) throw new Error('This deploy command requires a GitHub origin remote.');
const [, owner, repository] = match;
const base =
  repository.toLowerCase() === `${owner.toLowerCase()}.github.io` ? '/' : `/${repository}/`;
const sourceCommit = git(['rev-parse', 'HEAD']);
if (git(['status', '--porcelain']))
  throw new Error('Commit your changes before publishing a release.');

execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build'], {
  cwd: root,
  env: { ...process.env, RITME_BASE_PATH: base },
  stdio: 'inherit',
});
const directory = mkdtempSync(join(tmpdir(), 'ritme-pages-'));
try {
  git(['init', '--quiet'], directory);
  git(['remote', 'add', 'origin', remote], directory);
  const ref = git(['ls-remote', 'origin', 'refs/heads/gh-pages']);
  if (ref) {
    git(['fetch', '--depth=1', 'origin', 'gh-pages'], directory);
    git(['checkout', '--quiet', '-b', 'gh-pages', 'FETCH_HEAD'], directory);
    if (!existsSync(join(directory, '.ritme-pages'))) {
      throw new Error(
        'Existing gh-pages branch is not managed by Ritme; refusing to overwrite it.',
      );
    }
    for (const entry of readdirSync(directory)) {
      if (entry !== '.git') rmSync(join(directory, entry), { recursive: true, force: true });
    }
  }
  cpSync(join(root, 'dist'), directory, { recursive: true });
  writeFileSync(join(directory, '.nojekyll'), '');
  writeFileSync(join(directory, '.ritme-pages'), 'Generated by scripts/deploy-pages.mjs\n');
  writeFileSync(
    join(directory, 'deployment.json'),
    JSON.stringify({ sourceCommit, basePath: base, builtAt: new Date().toISOString() }) + '\n',
  );
  git(['config', 'user.name', git(['log', '-1', '--format=%an'])], directory);
  git(['config', 'user.email', git(['log', '-1', '--format=%ae'])], directory);
  git(['add', '--all'], directory);
  git(['commit', '--quiet', '-m', `Publish Ritme ${sourceCommit.slice(0, 7)}`], directory);
  execFileSync('git', ['push', 'origin', 'HEAD:gh-pages'], { cwd: directory, stdio: 'inherit' });
  console.log(`Published build files to ${owner}/${repository}, branch gh-pages.`);
  console.log(`Site address after GitHub Pages is enabled: https://${owner}.github.io${base}`);
  console.log('GitHub repository Settings → Pages → Deploy from a branch → gh-pages → / (root).');
} finally {
  rmSync(directory, { recursive: true, force: true });
}
